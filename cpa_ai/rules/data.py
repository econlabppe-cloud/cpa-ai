def tax_year(year: int) -> TaxYear:
    """טבלת מס לשנה. כשאין טבלה לשנה המבוקשת (למשל תכנון לשנה הבאה) משתמשים בטבלה האחרונה הידועה,
    ומסמנים זאת במפורש כלא מאומת — לא מחזירים שגיאה ולא מעמידים פנים שהטבלה ידועה."""
    if year in TAX_YEARS:
        return TAX_YEARS[year]
    earlier = [y for y in TAX_YEARS if y <= year]
    base_year = max(earlier) if earlier else min(TAX_YEARS)
    base = TAX_YEARS[base_year]
    return TaxYear(base.brackets, base.surtax_threshold, base.surtax_rate, base.credit_point_annual,
                   Source(base.source.citation, False, f"אין טבלה לשנת {year}; משמשת טבלת {base_year}. {base.source.note}"))

